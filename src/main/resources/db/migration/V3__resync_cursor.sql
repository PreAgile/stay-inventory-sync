-- ─────────────────────────────────────────────────────────────────────────────
-- V3 — 재동기화 진행 상태와 임대
--
-- 도메인 테이블이 아니다. 재동기화가 격자를 어디까지 훑었는지와, 인스턴스 하나만
-- 돌게 하는 임대를 담는다. 도메인 8개 + 운영 1개가 되는 지점이다.
--
-- 왜 필요한가 (#71 · #67)
--
--   #71  커서가 없어 매 주기 같은 앞 500건만 읽었다. 격자가 상한을 넘으면
--        501번째부터는 영원히 재동기화되지 않는다 -- 최종 방어선이 부분만 덮었다.
--
--   #67  방어가 없어 인스턴스 N대면 전량이 N번 나갔다. 스냅샷은 멱등키를
--        일부러 받지 않으므로 채널도 흡수하지 못한다.
--
-- 임대 방식은 Outbox 릴레이와 같다. 트랜잭션 락으로 잡으면 외부 호출 동안
-- 커넥션을 붙잡게 되므로, 조건부 UPDATE 로 미래 시각을 심고 곧 커밋한다.
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE resync_cursor (
    -- 단일 행이다. 격자를 훑는 진행점은 하나뿐이므로 행이 늘 이유가 없고,
    -- CHECK 로 못박아 두면 실수로 두 번째 행이 생겨 두 커서가 경쟁하는 일이 없다.
    -- INT 다. SMALLINT 로 두면 단일 행에서 얻는 것이 없는데 ERD 어휘에
    -- smallint 를 새로 들여야 하고, 그러면 대조 게이트의 타입 매핑이 늘어난다.
    id                INT          PRIMARY KEY,

    -- 키셋 커서. (room_type_id, stay_date) 순서로 훑고 이 값 **뒤**부터 읽는다.
    -- OFFSET 을 쓰지 않는 이유는 격자가 자라기 때문이다 -- 행이 앞에 끼어들면
    -- OFFSET 은 이미 보낸 것을 다시 보내거나 안 보낸 것을 건너뛴다.
    last_room_type_id BIGINT       NOT NULL DEFAULT 0,
    last_stay_date    DATE         NOT NULL DEFAULT DATE '0001-01-01',

    -- 커서가 어느 구간을 훑던 것인지. 요청 구간이 바뀌면 커서를 초기화해야 한다.
    --
    -- 없으면 조용한 거짓 성공이 난다 -- 스케줄러가 넓은 구간을 돌아 커서가 뒤로
    -- 가 있는데 운영자가 더 이른 구간을 수동 요청하면, 키셋 조건에 걸려 0건이
    -- 읽히고 "한 바퀴 완료" 로 보고된다. 실제로는 아무것도 나가지 않았다.
    window_from       DATE,
    window_to         DATE,

    -- 임대. 미래면 다른 인스턴스가 돌고 있다는 뜻이다.
    -- NULL 로 되돌리는 것이 정상 종료이고, 프로세스가 죽으면 시각이 지나 풀린다.
    leased_until      TIMESTAMPTZ,

    -- 임대 소유자. 펜싱 토큰이다.
    --
    -- 만료 시각만으로 관리하면 A 가 임대 시간을 넘겼을 때 B 가 임대를 잡고,
    -- 그 뒤 A 의 커서 기록과 해제가 **B 의 상태를 덮는다.** 그러면 C 까지
    -- 중복 실행된다. 모든 쓰기를 이 토큰 조건으로 제한해 A 의 뒤늦은 쓰기가
    -- rowcount 0 으로 떨어지게 한다 -- 잃은 것을 조용히 넘기지 않고 감지한다.
    lease_token       UUID,

    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT resync_cursor_singleton CHECK (id = 1)
);

-- 커서 행이 없으면 재동기화가 아무것도 하지 않는다. 마이그레이션에서 심는다 --
-- 애플리케이션이 첫 실행에 만들게 하면 인스턴스 둘이 동시에 만들려 할 수 있다.
